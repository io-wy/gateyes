	CreateAPIKey(*gin.Context)
	CreatePlugin(*gin.Context)
	CreateProject(*gin.Context)
	CreateProvider(*gin.Context)
	CreateRole(*gin.Context)
	CreateService(*gin.Context)
	CreateServiceSubscription(*gin.Context)
	CreateServiceVersion(*gin.Context)
	CreateTenant(*gin.Context)
	CreateUser(*gin.Context)
	CreateVirtualKey(*gin.Context)
	Dashboard(*gin.Context)
	DeletePlugin(*gin.Context)
	DeleteProject(*gin.Context)
	DeleteProvider(*gin.Context)
	DeleteRole(*gin.Context)
	DeleteService(*gin.Context)
	DeleteTenant(*gin.Context)
	DeleteUser(*gin.Context)
	DeleteVirtualKey(*gin.Context)
	GetAPIKey(*gin.Context)
	GetBudgets(*gin.Context)
	GetCacheSummary(*gin.Context)
	GetCatalog(*gin.Context)
	GetPlugin(*gin.Context)
	GetProject(*gin.Context)
	GetProjectUsage(*gin.Context)
	GetProvider(*gin.Context)
	GetProviderStats(*gin.Context)
	GetProviders(*gin.Context)
	GetResponseDetail(*gin.Context)
	GetResponseTrace(*gin.Context)
	GetRole(*gin.Context)
	GetService(*gin.Context)
	GetServiceSubscription(*gin.Context)
	GetTenant(*gin.Context)
	GetUsageBreakdown(*gin.Context)
